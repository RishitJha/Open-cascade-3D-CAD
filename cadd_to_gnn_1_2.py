def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()

def unique_count(shape, kind):
    m = TopTools_IndexedMapOfShape()
    TopExp.MapShapes_s(shape, kind, m)
    return m.Extent()

def process(filename):
    t0 = time.time()
    path = RAW_STEP_DIR / filename
    rec = {"filename": filename, "sha256": sha256(path),
           "classification": "read_failure", "error": ""}
    try:
        # Create the reader first, then set the unit (every read)
        reader = STEPControl_Reader()
        Interface_Static.SetCVal_s("xstep.cascade.unit", "MM")

        if reader.ReadFile(str(path)) != IFSelect_RetDone:
            raise RuntimeError("STEP could not be read")
        if reader.TransferRoots() == 0:
            raise RuntimeError("No roots transferred")
        shape = reader.OneShape()
        if shape.IsNull():
            raise RuntimeError("Null shape")

        rec["valid_brep"] = BRepCheck_Analyzer(shape).IsValid()
        rec["solids"]   = unique_count(shape, TopAbs_SOLID)
        rec["shells"]   = unique_count(shape, TopAbs_SHELL)
        rec["faces"]    = unique_count(shape, TopAbs_FACE)
        rec["edges"]    = unique_count(shape, TopAbs_EDGE)
        rec["vertices"] = unique_count(shape, TopAbs_VERTEX)

        if not rec["valid_brep"]:
            rec["classification"] = "invalid_brep"
            return rec

        vp = GProp_GProps(); BRepGProp.VolumeProperties_s(shape, vp)
        sp = GProp_GProps(); BRepGProp.SurfaceProperties_s(shape, sp)
        volume, area = abs(vp.Mass()), sp.Mass()

        box = Bnd_Box(); BRepBndLib.Add_s(shape, box)
        x0, y0, z0, x1, y1, z1 = box.Get()
        L, W, H = x1 - x0, y1 - y0, z1 - z0
        diag = float(np.sqrt(L**2 + W**2 + H**2))
        bvol = L * W * H

        vals = [volume, area, L, W, H, diag, bvol]
        if (min(rec["solids"], rec["faces"], rec["edges"], rec["vertices"]) <= 0
                or not np.isfinite(vals).all()
                or volume <= 0 or min(L, W, H) <= 0):
            rec["classification"] = "incomplete_topology"
            return rec

        rec.update({
            "volume": volume, "surface_area": area,
            "bbox_length": L, "bbox_width": W, "bbox_height": H,
            "bbox_diagonal": diag, "bbox_volume": bvol,
            "normalized_volume": volume / diag**3,
            "bbox_volume_fraction": volume / bvol,
            "classification": "primary_candidate",
        })
    except Exception as e:
        rec["error"] = str(e)
    finally:
        rec["time_seconds"] = round(time.time() - t0, 3)
    return rec

