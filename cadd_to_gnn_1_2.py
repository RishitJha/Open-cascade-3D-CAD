# ---------------------------------------------------------------------
# PART 3: Helper function 1 - read a STEP file into a 3D shape
# ---------------------------------------------------------------------
def load_shape(path):
    reader = STEPControl_Reader()                       # create the reader FIRST
    Interface_Static.SetCVal_s("xstep.cascade.unit", "MM")  # then set units to millimetres
    # ReadFile returns a status code. Anything other than "done" means failure.
    if reader.ReadFile(str(path)) != IFSelect_RetDone:
        raise RuntimeError("STEP could not be read")
    # TransferRoots converts the file's contents into a 3D shape. 0 = nothing converted.
    if reader.TransferRoots() == 0:
        raise RuntimeError("No roots transferred")
    shape = reader.OneShape()                           # the finished 3D shape
    if shape.IsNull():                                  # empty shape = something went wrong
        raise RuntimeError("Null shape")
    return shape


# ---------------------------------------------------------------------
# PART 4: Helper function 2 - list the UNIQUE faces / edges / vertices
# ---------------------------------------------------------------------
def unique_shapes(shape, kind):
    m = TopTools_IndexedMapOfShape()      # an empty numbered list
    TopExp.MapShapes_s(shape, kind, m)    # fill it with each unique part of that kind
    # CAD numbering starts at 1 (not 0), so we loop from 1 to Extent().
    # Returns: the numbered list itself, AND a normal Python list of the parts.
    return m, [m.FindKey(i) for i in range(1, m.Extent() + 1)]


# ---------------------------------------------------------------------
# PART 5: Helper function 3 - make connections go BOTH ways
# ---------------------------------------------------------------------
# A graph connection between A and B is stored as two arrows: A->B and B->A.
# 'pairs' is a list like [(0,1), (1,2)], 'feats' holds one feature list per pair.
def both_ways(pairs, feats, n_feat):
    if not pairs:   # no connections at all: return empty arrays of the right shape
        return (torch.empty((2, 0), dtype=torch.long),
                torch.empty((0, n_feat), dtype=torch.float))
    idx, attr = [], []
    for (a, b), f in zip(pairs, feats):   # go through each pair with its features
        idx += [(a, b), (b, a)]           # store both directions
        attr += [f, f]                    # both directions share the same features
    # Graph libraries want connections as a 2-row table: row 0 = from, row 1 = to.
    return (torch.tensor(idx, dtype=torch.long).T.contiguous(),
            torch.tensor(np.asarray(attr), dtype=torch.float))


# ---------------------------------------------------------------------
# PART 6: The main function - build all 4 graphs from one shape
# ---------------------------------------------------------------------
def build_graphs(shape, volume):

    # ===== Step A: measure the model's overall size =====
    box = Bnd_Box()                        # an empty bounding box
    BRepBndLib.Add_s(shape, box)           # stretch it to fit the shape
    x0, y0, z0, x1, y1, z1 = box.Get()     # the box corners (min and max for x, y, z)
    # Diagonal = the longest line from one corner of the box to the opposite corner.
    diag = float(np.sqrt((x1-x0)**2 + (y1-y0)**2 + (z1-z0)**2))
    if not np.isfinite(diag) or diag <= 0:   # a broken box would ruin every division below
        raise RuntimeError("Bad bounding box")
    # Centre of the box. Subtracting it moves every model to the same origin.
    center = np.array([(x0+x1)/2, (y0+y1)/2, (z0+z1)/2])

    # ===== Step B: list every unique face, edge and vertex =====
    # face_map etc. are the numbered lists, faces etc. are the plain Python lists.
    face_map,   faces    = unique_shapes(shape, TopAbs_FACE)
    edge_map,   edges    = unique_shapes(shape, TopAbs_EDGE)
    vertex_map, vertices = unique_shapes(shape, TopAbs_VERTEX)

    # ===== Step C: 14 numbers for every FACE =====
    # Order of the 14 numbers:
    #  [0-5]  surface type flags: plane, cylinder, cone, sphere, torus, other
    #  [6]    area / diag^2          (size-free area)
    #  [7]    radius / diag          (size-free radius)
    #  [8-10] axis direction x,y,z   (for cylinders and cones)
    #  [11-13] centre position x,y,z (size-free, around the model's centre)
    face_feats = []
    for fs in faces:
        face = TopoDS.Face_s(fs)               # treat the part as a face
        props = GProp_GProps()                 # a container for measurements
        BRepGProp.SurfaceProperties_s(face, props)   # measure this face
        area = props.Mass()                    # for surfaces, "Mass" means area
        c = props.CentreOfMass()               # the face's middle point
        # Move it so the model centre is (0,0,0), then divide by diag to remove size.
        centroid = (np.array([c.X(), c.Y(), c.Z()]) - center) / diag

        ad = BRepAdaptor_Surface(face, True)   # lets us ask what kind of surface it is
        t = ad.GetType()                       # the surface kind
        # Each flag is 1.0 if the face is that kind, otherwise 0.0.
        flags = [float(t == GeomAbs_Plane), float(t == GeomAbs_Cylinder),
                 float(t == GeomAbs_Cone),  float(t == GeomAbs_Sphere),
                 float(t == GeomAbs_Torus)]
        # "Other" (curvy B-spline surfaces etc.) = 1 if none of the five above matched.
        flags.append(1.0 - sum(flags))

        radius, axis = 0.0, np.zeros(3)        # defaults: no radius, no axis
        if t == GeomAbs_Cylinder:
            cyl = ad.Cylinder()                # get the cylinder's details
            radius = cyl.Radius()
            d = cyl.Axis().Direction()         # which way the cylinder points
            axis = np.array([d.X(), d.Y(), d.Z()])
        elif t == GeomAbs_Cone:
            d = ad.Cone().Axis().Direction()   # which way the cone points
            axis = np.array([d.X(), d.Y(), d.Z()])
        elif t == GeomAbs_Sphere:
            radius = ad.Sphere().Radius()

        # Join everything into one list of 14 numbers.
        face_feats.append(flags + [area / diag**2, radius / diag]
                          + list(axis) + list(centroid))
    face_x = np.asarray(face_feats, dtype=np.float32)   # list -> table of numbers

    # ===== Step D: 4 numbers for every EDGE =====
    # [0] length / diag, [1] is it a straight line, [2] is it a circle, [3] other curve
    edge_feats = []
    for es in edges:
        edge = TopoDS.Edge_s(es)               # treat the part as an edge
        props = GProp_GProps()
        BRepGProp.LinearProperties_s(edge, props)    # measure its length
        t = BRepAdaptor_Curve(edge).GetType()        # what kind of curve is it?
        is_line, is_circle = float(t == GeomAbs_Line), float(t == GeomAbs_Circle)
        edge_feats.append([props.Mass() / diag,      # for edges, "Mass" means length
                           is_line, is_circle,
                           1.0 - is_line - is_circle])   # "other" curve
    edge_x = np.asarray(edge_feats, dtype=np.float32)

    # ===== Step E: 3 numbers for every VERTEX =====
    # Just its position (x, y, z), centred and divided by diag.
    vertex_feats = []
    for vs in vertices:
        p = BRep_Tool.Pnt_s(TopoDS.Vertex_s(vs))     # the corner's 3D point
        vertex_feats.append((np.array([p.X(), p.Y(), p.Z()]) - center) / diag)
    vertex_x = np.asarray(vertex_feats, dtype=np.float32)

    # ===== Step F: work out WHO TOUCHES WHOM =====
    n_f, n_e, n_v = len(faces), len(edges), len(vertices)   # how many of each
    # Four lookup tables, all empty to begin with:
    edge_to_faces    = {i: set() for i in range(n_e)}   # which faces use this edge
    edge_to_vertices = {i: set() for i in range(n_e)}   # which corners end this edge
    vertex_to_edges  = {i: set() for i in range(n_v)}   # which edges meet at this corner
    face_to_edges    = [set() for _ in range(n_f)]      # which edges border this face

    # Fill them: for each face, find its edges.
    for fi, fs in enumerate(faces):                     # fi = face number (starts at 0)
        local, _ = unique_shapes(fs, TopAbs_EDGE)       # edges of just this face
        for j in range(1, local.Extent() + 1):
            # FindIndex gives the edge's number in the whole model (starts at 1), so subtract 1.
            ei = edge_map.FindIndex(local.FindKey(j)) - 1
            if ei >= 0:                                 # -1 would mean "not found"
                face_to_edges[fi].add(ei)
                edge_to_faces[ei].add(fi)

    # Fill them: for each edge, find its end corners.
    for ei, es in enumerate(edges):
        local, _ = unique_shapes(es, TopAbs_VERTEX)
        for j in range(1, local.Extent() + 1):
            vi = vertex_map.FindIndex(local.FindKey(j)) - 1
            if vi >= 0:
                edge_to_vertices[ei].add(vi)
                vertex_to_edges[vi].add(ei)

    # ===== Step G: FACE GRAPH (nodes = faces) =====
    # Two faces are connected if they share an edge.
    # The connection carries that shared edge's 4 numbers.
    pairs, feats = [], []
    for ei, fset in edge_to_faces.items():
        for a, b in combinations(sorted(fset), 2):      # every pair of faces on this edge
            pairs.append((a, b)); feats.append(edge_x[ei])
    f_index, f_attr = both_ways(pairs, feats, N_EDGE_FEATURES)

    # ===== Step H: EDGE GRAPH (nodes = edges) =====
    # Two edges are connected if they meet at a corner.
    # The connection carries that corner's 3 numbers.
    pairs, feats = [], []
    for vi in range(n_v):
        for a, b in combinations(sorted(vertex_to_edges[vi]), 2):
            pairs.append((a, b)); feats.append(vertex_x[vi])
    e_index, e_attr = both_ways(pairs, feats, N_VERTEX_FEATURES)

    # ===== Step I: VERTEX GRAPH (nodes = corners) =====
    # Each edge becomes a connection between its two end corners.
    # A closed circle edge has only 1 corner, so it is skipped (needs exactly 2).
    pairs, feats = [], []
    for ei, vset in edge_to_vertices.items():
        ends = sorted(vset)
        if len(ends) == 2:
            pairs.append((ends[0], ends[1])); feats.append(edge_x[ei])
    v_index, v_attr = both_ways(pairs, feats, N_EDGE_FEATURES)

    # ===== Step J: the target and extra labels =====
    # TARGET y = volume / diag^3. This number does not change if the part is scaled.
    y = torch.tensor([volume / diag**3], dtype=torch.float)
    # We also store the real volume and diag, but only as labels.
    # They are NOT inputs to the network; they let us convert predictions back later.
    labels = dict(y=y,
                  volume=torch.tensor([volume], dtype=torch.float),
                  diag=torch.tensor([diag], dtype=torch.float))

    # Pack each graph: x = node numbers, edge_index = who connects to whom,
    # edge_attr = numbers on each connection.
    face_g   = Data(x=torch.from_numpy(face_x),   edge_index=f_index, edge_attr=f_attr, **labels)
    edge_g   = Data(x=torch.from_numpy(edge_x),   edge_index=e_index, edge_attr=e_attr, **labels)
    vertex_g = Data(x=torch.from_numpy(vertex_x), edge_index=v_index, edge_attr=v_attr, **labels)

    # ===== Step K: HETERO GRAPH (all three node kinds together) =====
    # fe = list of (face, edge) pairs where the edge borders the face
    fe = [(f, e) for f, es in enumerate(face_to_edges) for e in sorted(es)]
    # ev = list of (edge, vertex) pairs where the corner ends the edge
    ev = [(e, v) for e, vs in edge_to_vertices.items() for v in sorted(vs)]
    # Small helper: turn a list of pairs into the 2-row table graph libraries want.
    to_idx = lambda p: (torch.tensor(p, dtype=torch.long).T.contiguous()
                        if p else torch.empty((2, 0), dtype=torch.long))
    fe_idx, ev_idx = to_idx(fe), to_idx(ev)

    hg = HeteroData()
    hg["face"].x   = torch.from_numpy(face_x)     # the three kinds of nodes
    hg["edge"].x   = torch.from_numpy(edge_x)
    hg["vertex"].x = torch.from_numpy(vertex_x)
    # Four kinds of connections: each one forwards, and each one backwards (.flip(0)
    # swaps the "from" row and the "to" row).
    hg["face", "boundary", "edge"].edge_index       = fe_idx
    hg["edge", "belongs_to", "face"].edge_index     = fe_idx.flip(0)
    hg["edge", "endpoint", "vertex"].edge_index     = ev_idx
    hg["vertex", "connected_by", "edge"].edge_index = ev_idx.flip(0)
    hg.y, hg.volume, hg.diag = y, labels["volume"], labels["diag"]

    # Return all four graphs plus the counts (used by the test below).
    return {"face": face_g, "edge": edge_g, "vertex": vertex_g, "hetero": hg,
            "counts": (n_f, n_e, n_v)}


