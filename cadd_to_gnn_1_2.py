# 3. Download one file (skips if already on Drive)
def download_step(item):
    name = item["name"]
    out  = RAW_STEP_DIR / name

    if out.exists() and out.stat().st_size == item["stepBytes"]:
        return {"filename": name, "status": "ALREADY_EXISTS"}

    try:
        r = requests.get(BASE_URL + item["path"], timeout=180)
        r.raise_for_status()
        data = gzip.decompress(r.content)

        if len(data) != item["stepBytes"]:
            raise ValueError(f"Size mismatch: {len(data)} vs {item['stepBytes']}")

        out.write_bytes(data)
        return {"filename": name, "status": "SUCCESS"}

    except Exception as e:
        return {"filename": name, "status": "FAILED", "error": str(e)}

# 4. Run both groups
def run_group(items, label):
    results, t0 = [], time.time()
    with ThreadPoolExecutor(max_workers=MAX_WORKERS) as ex:
        futures = [ex.submit(download_step, it) for it in items]
        for f in as_completed(futures):
            results.append(f.result())
    df = pd.DataFrame(results)
    print(f"\n{label}: {df['status'].value_counts().to_dict()} "
          f"({time.time()-t0:.0f}s)")
    return df

