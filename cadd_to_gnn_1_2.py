def compare_node_features(reference, stored, label):
    """
    Compare an independently extracted feature matrix with
    the feature matrix stored in a graph.

    Check:
    - Same matrix dimensions.
    - All values finite.
    - Numerical agreement within tolerance.
    """

    reference = np.asarray(reference, dtype=np.float32)
    stored = stored.detach().cpu().numpy()

    if reference.shape != stored.shape:
        return {
            "status": "SHAPE_MISMATCH",
            "max_error": np.nan
        }

    if not np.isfinite(stored).all():
        return {
            "status": "NONFINITE",
            "max_error": np.nan
        }

    difference = np.abs(reference - stored)
    max_error = float(difference.max()) if difference.size else 0.0

    # Allow a small floating-point tolerance.
    passed = np.allclose(
        reference,
        stored,
        rtol=1e-5,
        atol=1e-6,
        equal_nan=False
    )

    return {
        "status": "PASS" if passed else "VALUE_MISMATCH",
        "max_error": max_error
    }


def feature_key(values):
    """
    Convert a feature vector into a rounded tuple.

    This lets us compare edge attributes without depending
    on the order in which the graph builder stored connections.
    """
    values = np.asarray(values, dtype=np.float32)
    return tuple(np.round(values, 6).tolist())


def expected_connection_counter(pairs_and_features):
    """
    Build a multiset of directed connections and their features.

    A Counter is used because multiple B-Rep entities can produce
    connections between the same pair of graph nodes.
    """
    result = Counter()

    for source, target, features in pairs_and_features:

        result[(source, target, feature_key(features))] += 1

    return result


def actual_connection_counter(graph):
    """
    Read the stored graph connections and their edge attributes
    and convert them into the same Counter representation.
    """
    result = Counter()

    edge_index = graph.edge_index.detach().cpu().numpy()
    edge_attr = graph.edge_attr.detach().cpu().numpy()

    for i in range(edge_index.shape[1]):

        source = int(edge_index[0, i])
        target = int(edge_index[1, i])

        result[
            (source, target, feature_key(edge_attr[i]))
        ] += 1

    return result


