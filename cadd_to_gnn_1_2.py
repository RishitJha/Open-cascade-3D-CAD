def check_model(row, out):
    problems = []
    fg, eg, vg, hg = out["face"], out["edge"], out["vertex"], out["hetero"]

    # 1. Node counts agree with the counts saved in the CSV
    expected = (int(row["faces"]), int(row["edges"]), int(row["vertices"]))
    if out["counts"] != expected:
        problems.append(f"counts {out['counts']} != CSV {expected}")

    # 2. Feature sizes are 14 / 4 / 3
    if (fg.x.shape[1], eg.x.shape[1], vg.x.shape[1]) != (14, 4, 3):
        problems.append("wrong feature size")

    # 3. No NaN or infinity in any node or connection number
    for name, g in (("face", fg), ("edge", eg), ("vertex", vg)):
        if not torch.isfinite(g.x).all():
            problems.append(f"{name}: non-finite node features")
        if not torch.isfinite(g.edge_attr).all():
            problems.append(f"{name}: non-finite connection features")
        # 4. Every connection points at a node that exists
        if g.edge_index.numel() > 0:
            if int(g.edge_index.min()) < 0 or int(g.edge_index.max()) >= g.x.shape[0]:
                problems.append(f"{name}: connection index out of range")

    # 5. Hetero graph has the same node counts as the three simple graphs
    if (hg["face"].x.shape[0], hg["edge"].x.shape[0], hg["vertex"].x.shape[0]) != out["counts"]:
        problems.append("hetero node counts differ")

    # 6. The stored volume equals the CSV volume, and y = volume / diag^3
    vol_csv = float(row["volume"])
    if not np.isclose(float(fg.volume), vol_csv, rtol=1e-5):
        problems.append("stored volume differs from CSV")
    if not np.isclose(float(fg.y), vol_csv / float(fg.diag) ** 3, rtol=1e-4):
        problems.append("target is not volume / diag^3")

    # 7. All four graphs carry the same target
    for g in (eg, vg, hg):
        if not torch.allclose(fg.y, g.y):
            problems.append("targets differ between graph types")
            break

    return problems


