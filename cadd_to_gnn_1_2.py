features = np.log1p(features)                     # shrink huge values

fmin = features.min(axis=0)
frange = features.max(axis=0) - fmin
frange[frange == 0] = 1.0                         # avoid dividing by zero
scaled = (features - fmin) / frange               # every column now 0 to 1

# 3. Farthest-point sampling
centre = scaled.mean(axis=0)
first = int(np.argmin(((scaled - centre) ** 2).sum(axis=1)))

chosen = [first]
min_dist = np.linalg.norm(scaled - scaled[first], axis=1)

