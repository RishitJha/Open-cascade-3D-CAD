def load_audit_shape(step_path):
    """
    Independently reopen a STEP file and transfer its geometry.

    The unit setting matches the original project extraction.
    This function does not use or modify any saved graph.
    """

    reader = STEPControl_Reader()

    # Interpret STEP geometry in millimetres.
    Interface_Static.SetCVal_s(
        "xstep.cascade.unit",
        "MM"
    )

    # Read the STEP file.
    read_status = reader.ReadFile(str(step_path))

    if read_status != IFSelect_RetDone:
        raise RuntimeError("STEP file could not be read")

    # Transfer the STEP roots into an OpenCascade shape.
    transferred = reader.TransferRoots()

    if transferred == 0:
        raise RuntimeError("No STEP roots transferred")

    # Obtain the combined transferred shape.
    shape = reader.OneShape()

    if shape.IsNull():
        raise RuntimeError("Transferred shape is null")

    return shape


