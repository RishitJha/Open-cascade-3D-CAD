    nxt = int(np.argmax(min_dist))                # most different from the chosen set
    chosen.append(nxt)
    min_dist = np.minimum(min_dist, np.linalg.norm(scaled - scaled[nxt], axis=1))
    min_dist[chosen] = -1                         # never pick the same one twice

