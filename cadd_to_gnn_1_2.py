def inspect_model(filename, stored_row):
    """
    Independently inspect one STEP model.

    Calculate:
    - Original Add_s bounding box.
    - Tight AddOptimal_s bounding box.
    - Bounding-box diagonals and volumes.
    - Whole-shape volume and surface area.
    - Face, edge and vertex counts.
    - Sorted face-area and edge-length distributions.
    - Exact STEP file hash.
    """

    path = RAW_STEP_DIR / filename

    if not path.exists():
        raise FileNotFoundError(path)

    # Load the original STEP geometry.
    shape = load_audit_shape(path)

    # ------------------------------------------------
    # A. Original bounding box used by graph builder
    # ------------------------------------------------

    loose_box = Bnd_Box()

    BRepBndLib.Add_s(
        shape,
        loose_box
    )

    lx0, ly0, lz0, lx1, ly1, lz1 = loose_box.Get()

    loose_dimensions = np.array([
        lx1 - lx0,
        ly1 - ly0,
        lz1 - lz0
    ], dtype=float)

    loose_diagonal = float(
        np.linalg.norm(loose_dimensions)
    )

    loose_bbox_volume = float(
        np.prod(loose_dimensions)
    )

    # ------------------------------------------------
    # B. Tighter bounding box
    # ------------------------------------------------

    tight_box = Bnd_Box()

    BRepBndLib.AddOptimal_s(
        shape,
        tight_box,
        False,
        False
    )

    tx0, ty0, tz0, tx1, ty1, tz1 = tight_box.Get()

    tight_dimensions = np.array([
        tx1 - tx0,
        ty1 - ty0,
        tz1 - tz0
    ], dtype=float)

    tight_diagonal = float(
        np.linalg.norm(tight_dimensions)
    )

    tight_bbox_volume = float(
        np.prod(tight_dimensions)
    )

    if loose_diagonal <= 0 or tight_diagonal <= 0:
        raise RuntimeError("Invalid bounding-box diagonal")

    # ------------------------------------------------
    # C. Whole-shape geometric properties
    # ------------------------------------------------

    volume_props = GProp_GProps()

    BRepGProp.VolumeProperties_s(
        shape,
        volume_props
    )

    independent_volume = float(
        volume_props.Mass()
    )

    area_props = GProp_GProps()

    BRepGProp.SurfaceProperties_s(
        shape,
        area_props
    )

    independent_area = float(
        area_props.Mass()
    )

    # ------------------------------------------------
    # D. Enumerate topological entities
    # ------------------------------------------------

    faces = get_entities(shape, TopAbs_FACE)
    edges = get_entities(shape, TopAbs_EDGE)
    vertices = get_entities(shape, TopAbs_VERTEX)

    # ------------------------------------------------
    # E. Calculate sorted face-area distribution
    # ------------------------------------------------

    face_areas = []

    for face_shape in faces:

        face = TopoDS.Face_s(face_shape)

        props = GProp_GProps()

        BRepGProp.SurfaceProperties_s(
            face,
            props
        )

        face_areas.append(
            float(props.Mass())
        )

    face_areas = np.sort(
        np.asarray(face_areas, dtype=float)
    )

    # ------------------------------------------------
    # F. Calculate sorted edge-length distribution
    # ------------------------------------------------

    edge_lengths = []

    for edge_shape in edges:

        edge = TopoDS.Edge_s(edge_shape)

        props = GProp_GProps()

        BRepGProp.LinearProperties_s(
            edge,
            props
        )

        edge_lengths.append(
            float(props.Mass())
        )

    edge_lengths = np.sort(
        np.asarray(edge_lengths, dtype=float)
    )

    # ------------------------------------------------
    # G. Stored dataset values
    # ------------------------------------------------

    stored_volume = float(stored_row["volume"])
    stored_area = float(stored_row["surface_area"])
    stored_diagonal = float(stored_row["bbox_diagonal"])

    # ------------------------------------------------
    # H. Normalization impact
    # ------------------------------------------------

    # The original target is V / loose_diagonal^3.
    y_loose = independent_volume / loose_diagonal**3

    # This is a diagnostic alternative, not a replacement target.
    y_tight = independent_volume / tight_diagonal**3

    # Relative increase in the original bounding-box volume
    # compared with the tight bounding-box volume.
    bbox_inflation_percent = (
        (loose_bbox_volume / tight_bbox_volume) - 1
    ) * 100

    # Relative diagonal difference.
    diagonal_inflation_percent = (
        (loose_diagonal / tight_diagonal) - 1
    ) * 100

    # Effect on normalized volume target if the tight diagonal
    # were used instead of the original loose diagonal.
    target_change_percent = (
        (y_tight / y_loose) - 1
    ) * 100

    return {

        "filename": filename,

        "sha256": sha256_file(path),

        "faces": len(faces),
        "edges": len(edges),
        "vertices": len(vertices),

        "independent_volume": independent_volume,
        "stored_volume": stored_volume,

        "independent_surface_area": independent_area,
        "stored_surface_area": stored_area,

        "loose_x": loose_dimensions[0],
        "loose_y": loose_dimensions[1],
        "loose_z": loose_dimensions[2],

        "tight_x": tight_dimensions[0],
        "tight_y": tight_dimensions[1],
        "tight_z": tight_dimensions[2],

        "loose_diagonal": loose_diagonal,
        "tight_diagonal": tight_diagonal,

        "stored_diagonal": stored_diagonal,

        "loose_bbox_volume": loose_bbox_volume,
        "tight_bbox_volume": tight_bbox_volume,

        "bbox_inflation_percent": bbox_inflation_percent,

        "diagonal_inflation_percent": diagonal_inflation_percent,

        "original_normalized_volume": y_loose,
        "tight_normalized_volume_diagnostic": y_tight,

        "target_change_percent_if_tight": target_change_percent,

        # Keep sorted geometric distributions for pairwise
        # duplicate screening. These are not model inputs.
        "_face_areas": face_areas,
        "_edge_lengths": edge_lengths,

        # Preserve dimensions as arrays for pairwise comparison.
        "_loose_dimensions": loose_dimensions,
        "_tight_dimensions": tight_dimensions
    }


