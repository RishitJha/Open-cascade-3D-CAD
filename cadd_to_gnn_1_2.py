def load_shape(path):
    # Same safe reader as before: create reader first, then set millimetres.
    reader = STEPControl_Reader()
    Interface_Static.SetCVal_s("xstep.cascade.unit", "MM")
    if reader.ReadFile(str(path)) != IFSelect_RetDone:
        raise RuntimeError("STEP could not be read")
    if reader.TransferRoots() == 0:
        raise RuntimeError("No roots transferred")
    shape = reader.OneShape()
    if shape.IsNull():
        raise RuntimeError("Null shape")
    return shape


def unique(shape, kind):
    # Numbered list of unique faces / edges / vertices / solids,
    # plus the same parts as a normal Python list.
    m = TopTools_IndexedMapOfShape()
    TopExp.MapShapes_s(shape, kind, m)
    return m, [m.FindKey(i) for i in range(1, m.Extent() + 1)]


def bbox_diag(shape, tight):
    # Diagonal of the bounding box. tight=True asks OCC for the tightest box.
    box = Bnd_Box()
    if tight:
        BRepBndLib.AddOptimal_s(shape, box, False, False)
    else:
        BRepBndLib.Add_s(shape, box)
    x0, y0, z0, x1, y1, z1 = box.Get()
    return float(np.sqrt((x1-x0)**2 + (y1-y0)**2 + (z1-z0)**2))


def mesh_volume(shape, faces, diag):
    # Second, independent way to get volume: cut every face into triangles
    # and add up the signed volume of the tetrahedra they form with the origin.
    from OCP.BRepMesh import BRepMesh_IncrementalMesh
    from OCP.TopLoc import TopLoc_Location
    BRepMesh_IncrementalMesh(shape, MESH_DEFLECTION * diag, False, 0.3, True)
    total = 0.0
    for f in faces:
        face = TopoDS.Face_s(f)
        loc = TopLoc_Location()
        tri = BRep_Tool.Triangulation_s(face, loc)
        if tri is None:
            continue
        trsf = loc.Transformation()
        flip = (face.Orientation() == TopAbs_REVERSED)
        for i in range(1, tri.NbTriangles() + 1):
            n1, n2, n3 = tri.Triangle(i).Get()
            pts = [tri.Node(n).Transformed(trsf) for n in (n1, n2, n3)]
            if flip:
                pts[1], pts[2] = pts[2], pts[1]
            a, b, c = [np.array([p.X(), p.Y(), p.Z()]) for p in pts]
            total += float(np.dot(a, np.cross(b, c))) / 6.0
    return abs(total)


def pair_counter(edge_index):
    # Turn a 2-row connection table into a Counter of (from, to) pairs.
    return Counter(map(tuple, edge_index.T.tolist()))


def mismatch(expected, actual):
    # Number of pairs that are missing plus pairs that should not be there.
    return sum((expected - actual).values()) + sum((actual - expected).values())


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


