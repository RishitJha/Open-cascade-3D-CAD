def relative_difference(a, b):
    """
    Calculate symmetric relative difference.

    The denominator is the larger absolute magnitude,
    avoiding division by zero for small values.
    """

    denominator = max(
        abs(float(a)),
        abs(float(b)),
        1e-12
    )

    return abs(float(a) - float(b)) / denominator


def distribution_difference(a, b):
    """
    Compare two sorted arrays of face areas or edge lengths.

    Arrays must have the same number of elements.
    Returns the maximum symmetric relative difference.
    """

    if len(a) != len(b):
        return np.inf

    if len(a) == 0:
        return 0.0

    differences = [
        relative_difference(x, y)
        for x, y in zip(a, b)
    ]

    return float(max(differences))


