def feature_key(values):
    """
    Convert an edge-attribute vector into a rounded tuple.

    Rounding to six decimal places is retained from the original
    audit to avoid insignificant floating-point differences.
    """

    values = np.asarray(
        values,
        dtype=np.float32
    )

    return tuple(
        np.round(values, 6).tolist()
    )


def expected_connection_counter(pairs_and_features):
    """
    Construct a multiset of expected directed graph connections.

    Each entry contains:
    source index, target index and associated edge features.

    Counter preserves multiplicity if multiple B-Rep entities
    generate connections between the same node pair.
    """

    result = Counter()

    for source, target, features in pairs_and_features:

        result[
            (source, target, feature_key(features))
        ] += 1

    return result


def actual_connection_counter(graph):
    """
    Extract directed connections and edge attributes from
    an existing homogeneous graph.
    """

    result = Counter()

    edge_index = graph.edge_index.detach().cpu().numpy()
    edge_attr = graph.edge_attr.detach().cpu().numpy()

    if edge_index.shape[1] != edge_attr.shape[0]:
        raise RuntimeError(
            "Graph edge_index and edge_attr counts disagree"
        )

    for i in range(edge_index.shape[1]):

        source = int(edge_index[0, i])
        target = int(edge_index[1, i])

        result[
            (source, target, feature_key(edge_attr[i]))
        ] += 1

    return result


