# ------------------------------------------------------------

def train_edge_epoch():

    edge_model.train()

    total_loss = 0.0

    # Process each training CAD graph independently.
    for model_id, graph in edge_train_graphs.items():

        edge_optimizer.zero_grad()

        x = graph.x.float().to(EDGE_DEVICE)
        edge_index = graph.edge_index.long().to(EDGE_DEVICE)

        target = graph.y.float().reshape(1, 1).to(EDGE_DEVICE)

        # Forward pass: predict normalized volume.
        prediction = edge_model(x, edge_index)

        # Calculate squared prediction error.
        loss = edge_criterion(prediction, target)

        # Backpropagation: calculate gradients.
        loss.backward()

        # Update EdgeGCN parameters.
        edge_optimizer.step()

        total_loss += loss.item()

    return total_loss / len(edge_train_graphs)


# ------------------------------------------------------------
# 3. DEFINE VALIDATION FUNCTION
# ------------------------------------------------------------

def validate_edge():

    edge_model.eval()

    total_loss = 0.0

    # No gradients or parameter updates during validation.
    with torch.no_grad():

        for model_id, graph in edge_validation_graphs.items():

            x = graph.x.float().to(EDGE_DEVICE)
            edge_index = graph.edge_index.long().to(EDGE_DEVICE)

            target = graph.y.float().reshape(1, 1).to(EDGE_DEVICE)

            prediction = edge_model(x, edge_index)

            loss = edge_criterion(prediction, target)

            total_loss += loss.item()

    return total_loss / len(edge_validation_graphs)


