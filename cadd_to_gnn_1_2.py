# ---------------------------------------------------------------------
# PART 2: Turn each model's graphs into a short list of summary numbers.
# Only numbers already inside the graphs are used (all scale-free).
# Nothing here uses the volume.
# ---------------------------------------------------------------------
def summarise(name):
    fx = face_g[name].x.numpy()        # 14 numbers per face
    ex = edge_g[name].x.numpy()        # 4 numbers per edge
    nv = vertex_g[name].x.shape[0]     # number of vertices
    nf, ne = len(fx), len(ex)

    area = fx[:, 6]                    # face area / diag^2
    total_area = area.sum()

    return {
        # how many parts
        "log_faces":    np.log(nf),
        "log_edges":    np.log(ne),
        "log_vertices": np.log(nv),
        # what kinds of faces (fractions add up to 1)
        "frac_plane":    fx[:, 0].mean(),
        "frac_cylinder": fx[:, 1].mean(),
        "frac_cone":     fx[:, 2].mean(),
        "frac_sphere":   fx[:, 3].mean(),
        "frac_torus":    fx[:, 4].mean(),
        "frac_other":    fx[:, 5].mean(),
        # how much surface, and how it is spread
        "total_area_norm":     total_area,
        "log_total_area_norm": np.log(total_area + 1e-12),
        "max_face_area":       area.max(),
        "mean_face_area":      area.mean(),
        # edges
        "edge_length_sum":     ex[:, 0].sum(),
        "frac_line_edges":     ex[:, 1].mean(),
        "frac_circle_edges":   ex[:, 2].mean(),
        "frac_other_edges":    ex[:, 3].mean(),
        # how spread out the faces are around the model's centre
        "centroid_spread":     fx[:, 11:14].std(axis=0).mean(),
    }

X_df = pd.DataFrame([summarise(n) for n in names], index=names)
y = np.array([float(face_g[n].y) for n in names])        # target: volume / diag^3
y_log = np.log(y)

assert np.isfinite(X_df.to_numpy()).all(), "non-finite summary feature"
assert (y > 0).all()
print("Summary features per model:", X_df.shape[1])
print("Target range:", y.min().round(5), "to", y.max().round(5))

X = X_df.to_numpy()
index_of = {n: i for i, n in enumerate(names)}

# ---------------------------------------------------------------------
# PART 3: The models to compare
# ---------------------------------------------------------------------
def fit_predict(kind, train_idx, test_idx):
    """Fit on train_idx, return predictions (in the original y units) for test_idx."""
    if kind == "mean":                      # always predict the training average
        return np.full(len(test_idx), y[train_idx].mean())
    if kind == "geometric_mean":            # average on the log scale
        return np.full(len(test_idx), np.exp(y_log[train_idx].mean()))
    if kind == "ridge_log":                 # straight-line model on the log target
        m = make_pipeline(StandardScaler(),
                          RidgeCV(alphas=np.logspace(-3, 3, 25)))
    elif kind == "forest_log":              # many small decision trees
        m = RandomForestRegressor(n_estimators=300, min_samples_leaf=2,
                                  random_state=0, n_jobs=-1)
    else:
        raise ValueError(kind)
    m.fit(X[train_idx], y_log[train_idx])
    return np.exp(m.predict(X[test_idx]))

KINDS = ["mean", "geometric_mean", "ridge_log", "forest_log"]

def metrics(true, pred):
    rel = np.abs(pred - true) / true * 100            # relative error in %
    # Because volume = y * diag^3 and diag is known, the relative error of the
    # volume equals the relative error of y. So this is also the volume error.
    return {
        "R2":                r2_score(true, pred),
        "R2_on_log":         r2_score(np.log(true), np.log(pred)),
        "MAE":               mean_absolute_error(true, pred),
        "median_rel_err_%":  float(np.median(rel)),
    }

# ---------------------------------------------------------------------
# PART 4: Your shared split (70 train / 15 validation / 15 test)
# ---------------------------------------------------------------------
idx = {s: np.array([index_of[n] for n in split.loc[split["split"] == s, "filename"]])
       for s in ("train", "validation", "test")}
print("Split sizes:", {k: len(v) for k, v in idx.items()})

rows = []
for kind in KINDS:
    for part in ("validation", "test"):
        pred = fit_predict(kind, idx["train"], idx[part])
        rows.append({"model": kind, "set": part, **metrics(y[idx[part]], pred)})

split_table = pd.DataFrame(rows)
print("\n===== SHARED SPLIT (fit on the 70 training models) =====")
print(split_table.round(4).to_string(index=False))

# ---------------------------------------------------------------------
# PART 5: Repeated 5-fold cross-validation over all 100 models.
# The three near-identical models (00000011, 00000012, 00000207) are
# kept together in one group so they can never leak across folds.
# ---------------------------------------------------------------------
group_of = {}
for n in names:
    group_of[n] = "dup" if n[:8] in ("00000011", "00000012", "00000207") else n
groups = sorted(set(group_of.values()))

N_REPEATS, N_FOLDS = 5, 5
cv_rows = []
for repeat in range(N_REPEATS):
    rng = np.random.default_rng(repeat)
    order = rng.permutation(len(groups))
    fold_of_group = {groups[g]: k % N_FOLDS for k, g in enumerate(order)}
    fold = np.array([fold_of_group[group_of[n]] for n in names])

    for f in range(N_FOLDS):
        test_idx  = np.where(fold == f)[0]
        train_idx = np.where(fold != f)[0]
        for kind in KINDS:
            pred = fit_predict(kind, train_idx, test_idx)
            cv_rows.append({"model": kind, "repeat": repeat, "fold": f,
                            **metrics(y[test_idx], pred)})

cv = pd.DataFrame(cv_rows)
cv_summary = (cv.groupby("model")[["R2", "R2_on_log", "median_rel_err_%"]]
                .agg(["mean", "std"]).round(3).loc[KINDS])

print("\n===== REPEATED 5-FOLD CV, ALL 100 MODELS (5 repeats x 5 folds) =====")
print(cv_summary.to_string())

