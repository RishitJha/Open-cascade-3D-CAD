def compare_node_features(reference, stored):
    """
    Compare independently extracted features with saved graph
    node features.

    Uses the original numerical tolerances:
    rtol = 1e-5
    atol = 1e-6
    """

    reference = np.asarray(
        reference,
        dtype=np.float32
    )

    stored = stored.detach().cpu().numpy()

    if reference.shape != stored.shape:

        return {
            "status": "SHAPE_MISMATCH",
            "max_error": np.nan
        }

    if not np.isfinite(reference).all():

        return {
            "status": "REFERENCE_NONFINITE",
            "max_error": np.nan
        }

    if not np.isfinite(stored).all():

        return {
            "status": "STORED_NONFINITE",
            "max_error": np.nan
        }

    difference = np.abs(reference - stored)

    max_error = (
        float(difference.max())
        if difference.size
        else 0.0
    )

    passed = np.allclose(
        reference,
        stored,
        rtol=1e-5,
        atol=1e-6,
        equal_nan=False
    )

    return {
        "status": "PASS" if passed else "VALUE_MISMATCH",
        "max_error": max_error
    }


