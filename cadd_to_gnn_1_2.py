def verify_model(name, volume_csv, g):
    shape = load_shape(RAW_STEP_DIR / name)
    rec = {"filename": name}

    face_map,   faces    = unique(shape, TopAbs_FACE)
    edge_map,   edges    = unique(shape, TopAbs_EDGE)
    vertex_map, vertices = unique(shape, TopAbs_VERTEX)
    n_e = len(edges)
    n_v = len(vertices)

    # ---- A. Rebuild the connections with a DIFFERENT method ----------
    # The extractor looked inside each face and each edge.
    # Here we ask OCC directly: "which faces use this edge?" and
    # "which edges meet at this vertex?" (ancestor maps).
    ef = TopTools_IndexedDataMapOfShapeListOfShape()
    TopExp.MapShapesAndAncestors_s(shape, TopAbs_EDGE, TopAbs_FACE, ef)
    ve = TopTools_IndexedDataMapOfShapeListOfShape()
    TopExp.MapShapesAndAncestors_s(shape, TopAbs_VERTEX, TopAbs_EDGE, ve)

    edge_faces = {i: set() for i in range(n_e)}
    for k in range(1, ef.Extent() + 1):
        ei = edge_map.FindIndex(ef.FindKey(k)) - 1
        for f in ef.FindFromIndex(k):
            fi = face_map.FindIndex(f) - 1
            if ei >= 0 and fi >= 0:
                edge_faces[ei].add(fi)

    edge_verts = {i: set() for i in range(n_e)}
    vert_edges = {i: set() for i in range(n_v)}
    for k in range(1, ve.Extent() + 1):
        vi = vertex_map.FindIndex(ve.FindKey(k)) - 1
        for e in ve.FindFromIndex(k):
            ei = edge_map.FindIndex(e) - 1
            if vi >= 0 and ei >= 0:
                edge_verts[ei].add(vi)
                vert_edges[vi].add(ei)

    exp_face, exp_edge, exp_vertex = Counter(), Counter(), Counter()
    for ei, fs in edge_faces.items():                 # face graph
        for a, b in combinations(sorted(fs), 2):
            exp_face[(a, b)] += 1; exp_face[(b, a)] += 1
    for vi, es in vert_edges.items():                 # edge graph
        for a, b in combinations(sorted(es), 2):
            exp_edge[(a, b)] += 1; exp_edge[(b, a)] += 1
    for ei, vs in edge_verts.items():                 # vertex graph
        vs = sorted(vs)
        if len(vs) == 2:
            exp_vertex[(vs[0], vs[1])] += 1; exp_vertex[(vs[1], vs[0])] += 1
    exp_fe = Counter((f, e) for e, fs in edge_faces.items() for f in fs)
    exp_ev = Counter((e, v) for e, vs in edge_verts.items() for v in vs)

    hg = g["hetero"]
    rec["bad_face_links"]   = mismatch(exp_face,   pair_counter(g["face"].edge_index))
    rec["bad_edge_links"]   = mismatch(exp_edge,   pair_counter(g["edge"].edge_index))
    rec["bad_vertex_links"] = mismatch(exp_vertex, pair_counter(g["vertex"].edge_index))
    rec["bad_face_edge"]    = mismatch(exp_fe, pair_counter(hg["face", "boundary", "edge"].edge_index))
    rec["bad_edge_vertex"]  = mismatch(exp_ev, pair_counter(hg["edge", "endpoint", "vertex"].edge_index))

    # ---- B. Is the shape a closed, manifold solid? ----------------------
    # In a closed solid every edge is used exactly twice by faces
    # (a seam edge is used twice by the SAME face). Count the uses.
    uses = Counter()
    for f in faces:
        ex = TopExp_Explorer(f, TopAbs_EDGE)
        while ex.More():
            uses[edge_map.FindIndex(ex.Current()) - 1] += 1
            ex.Next()
    free = nonmanifold = 0
    for ei, e in enumerate(edges):
        try:
            if BRep_Tool.Degenerated_s(TopoDS.Edge_s(e)):   # zero-length edges at poles
                continue
        except Exception:
            pass
        if uses[ei] < 2:
            free += 1            # open boundary
        elif uses[ei] > 2:
            nonmanifold += 1     # three or more faces on one edge
    rec["free_edges"] = free
    rec["nonmanifold_edges"] = nonmanifold

    # ---- C. Volume label integrity -------------------------------------
    props = GProp_GProps()
    BRepGProp.VolumeProperties_s(shape, props)
    signed_total = float(props.Mass())
    solid_map, solids = unique(shape, TopAbs_SOLID)
    sum_abs = 0.0
    for s in solids:
        p = GProp_GProps()
        BRepGProp.VolumeProperties_s(TopoDS.Solid_s(s), p)
        sum_abs += abs(float(p.Mass()))

    rec["n_solids"] = len(solids)
    rec["signed_volume_negative"] = signed_total < 0
    rec["vol_rel_diff_vs_csv"] = abs(abs(signed_total) - volume_csv) / max(volume_csv, 1e-30)
    rec["vol_rel_diff_vs_solid_sum"] = abs(abs(signed_total) - sum_abs) / max(abs(signed_total), 1e-30)

    # ---- D. Is the bounding box tight? ----------------------------------
    diag_loose = bbox_diag(shape, tight=False)
    try:
        diag_tight = bbox_diag(shape, tight=True)
        rec["bbox_inflation"] = diag_loose / diag_tight - 1.0
    except Exception:
        rec["bbox_inflation"] = np.nan

    # ---- E. Mesh-based volume (optional, skipped for big models) ----------
    rec["mesh_rel_diff"] = np.nan
    if DO_MESH and len(faces) <= MESH_MAX_FACES:
        try:
            mv = mesh_volume(shape, faces, diag_loose)
            rec["mesh_rel_diff"] = abs(mv - volume_csv) / max(volume_csv, 1e-30)
        except Exception:
            pass
    return rec


