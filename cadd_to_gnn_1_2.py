HETERO_INPUT_DIMS = {
    "face": 14,
    "edge": 4,
    "vertex": 3
}

for graph in hetero_train_graphs.values():

    assert set(graph.node_types) == set(HETERO_NODE_TYPES)

    for node_type, expected_dim in HETERO_INPUT_DIMS.items():

        assert graph[node_type].x.shape[1] == expected_dim

    assert set(graph.edge_types) == set(HETERO_EDGE_TYPES)

# ------------------------------------------------------------
# 4. DEFINE HETEROGENEOUS GCN ARCHITECTURE
# ------------------------------------------------------------

class HeterogeneousGCN(nn.Module):

    def __init__(self):

        super().__init__()

        # ----------------------------------------------------
        # Layer 1: Original feature dimensions -> 64
        # Each relation has its own GraphConv operator.
        # ----------------------------------------------------

        self.conv1 = HeteroConv({

            ("face", "boundary", "edge"): GraphConv(
                (14, 4), HETERO_HIDDEN_DIM
            ),

            ("edge", "belongs_to", "face"): GraphConv(
                (4, 14), HETERO_HIDDEN_DIM
            ),

            ("edge", "endpoint", "vertex"): GraphConv(
                (4, 3), HETERO_HIDDEN_DIM
            ),

            ("vertex", "connected_by", "edge"): GraphConv(
                (3, 4), HETERO_HIDDEN_DIM
            )

        }, aggr="sum")

        # ----------------------------------------------------
        # Layers 2 and 3: 64 -> 64
        # ----------------------------------------------------

        self.conv2 = HeteroConv({

            edge_type: GraphConv(
                (HETERO_HIDDEN_DIM, HETERO_HIDDEN_DIM),
                HETERO_HIDDEN_DIM
            )

            for edge_type in HETERO_EDGE_TYPES

        }, aggr="sum")

        self.conv3 = HeteroConv({

            edge_type: GraphConv(
                (HETERO_HIDDEN_DIM, HETERO_HIDDEN_DIM),
                HETERO_HIDDEN_DIM
            )

            for edge_type in HETERO_EDGE_TYPES

        }, aggr="sum")

        self.dropout = HETERO_DROPOUT

        # Regression head: 64 -> 32 -> 1.
        self.regressor = nn.Sequential(
            nn.Linear(HETERO_HIDDEN_DIM, 32),
            nn.ReLU(),
            nn.Linear(32, 1)
        )

    def forward(self, x_dict, edge_index_dict):

        # First heterogeneous message-passing layer.
        x_dict = self.conv1(x_dict, edge_index_dict)

        x_dict = {
            node_type: torch.relu(x)
            for node_type, x in x_dict.items()
        }

        x_dict = {
            node_type: torch.nn.functional.dropout(
                x,
                p=self.dropout,
                training=self.training
            )
            for node_type, x in x_dict.items()
        }

        # Second heterogeneous message-passing layer.
        x_dict = self.conv2(x_dict, edge_index_dict)

        x_dict = {
            node_type: torch.relu(x)
            for node_type, x in x_dict.items()
        }

        x_dict = {
            node_type: torch.nn.functional.dropout(
                x,
                p=self.dropout,
                training=self.training
            )
            for node_type, x in x_dict.items()
        }

        # Third heterogeneous message-passing layer.
        x_dict = self.conv3(x_dict, edge_index_dict)

        x_dict = {
            node_type: torch.relu(x)
            for node_type, x in x_dict.items()
        }

        # Mean-pool each node type independently.
        pooled_embeddings = [
            x_dict[node_type].mean(dim=0)
            for node_type in HETERO_NODE_TYPES
        ]

        # Average the three type-level graph embeddings.
        # Each node type contributes equally to the final
        # 64-dimensional graph representation.
        graph_embedding = torch.stack(
            pooled_embeddings,
            dim=0
        ).mean(dim=0, keepdim=True)

        # Predict normalized volume.
        prediction = self.regressor(graph_embedding)

        return prediction


