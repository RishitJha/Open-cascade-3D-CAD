def independent_entity_map(shape, kind):
    """
    Independently enumerate unique B-Rep entities.

    A fresh indexed map is constructed for each call.
    The returned entity ordering is used consistently when
    constructing the reference feature matrices and relationships.
    """

    indexed_map = TopTools_IndexedMapOfShape()

    # Map all entities of the requested topological type.
    TopExp.MapShapes_s(
        shape,
        kind,
        indexed_map
    )

    # OpenCascade indexed maps start at index 1.
    entities = [
        indexed_map.FindKey(i)
        for i in range(1, indexed_map.Extent() + 1)
    ]

    return indexed_map, entities


