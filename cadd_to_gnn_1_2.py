def independent_entity_map(shape, kind):
    """
    Extract unique B-Rep entities using a fresh indexed map.

    This reproduces the intended entity enumeration independently,
    without calling the original unique_shapes() function.
    """
    indexed_map = TopTools_IndexedMapOfShape()
    TopExp.MapShapes_s(shape, kind, indexed_map)

    # OpenCascade uses indices starting at 1.
    entities = [
        indexed_map.FindKey(i)
        for i in range(1, indexed_map.Extent() + 1)
    ]

    return indexed_map, entities


def extract_reference_features(shape):
    """
    Independently calculate the expected numerical node features
    and B-Rep relationships for one STEP-derived shape.

    The formulas match the documented feature definitions in
    the original build_graphs() code.
    """

    # Calculate the same bounding box used by the original graph code.
    box = Bnd_Box()
    BRepBndLib.Add_s(shape, box)

    x0, y0, z0, x1, y1, z1 = box.Get()

    # Calculate the bounding-box diagonal and centre.
    diag = float(np.sqrt(
        (x1 - x0)**2 +
        (y1 - y0)**2 +
        (z1 - z0)**2
    ))

    if not np.isfinite(diag) or diag <= 0:
        raise RuntimeError("Invalid bounding-box diagonal")

    center = np.array([
        (x0 + x1) / 2,
        (y0 + y1) / 2,
        (z0 + z1) / 2
    ])

    # Independently enumerate all three B-Rep entity types.
    face_map, faces = independent_entity_map(shape, TopAbs_FACE)
    edge_map, edges = independent_entity_map(shape, TopAbs_EDGE)
    vertex_map, vertices = independent_entity_map(shape, TopAbs_VERTEX)

    # ============================================================
    # A. FACE FEATURES: 14 values per face
    # ============================================================

    face_features = []

    for face_shape in faces:

        face = TopoDS.Face_s(face_shape)

        # Calculate the face area and centre of mass.
        props = GProp_GProps()
        BRepGProp.SurfaceProperties_s(face, props)

        area = props.Mass()
        c = props.CentreOfMass()

        # Normalize the face centroid relative to the model centre.
        centroid = (
            np.array([c.X(), c.Y(), c.Z()]) - center
        ) / diag

        # Determine the geometric surface type.
        adaptor = BRepAdaptor_Surface(face, True)
        surface_type = adaptor.GetType()

        # Create the six surface-type indicators.
        flags = [
            float(surface_type == GeomAbs_Plane),
            float(surface_type == GeomAbs_Cylinder),
            float(surface_type == GeomAbs_Cone),
            float(surface_type == GeomAbs_Sphere),
            float(surface_type == GeomAbs_Torus)
        ]

        # Any other surface type is assigned to the sixth category.
        flags.append(1.0 - sum(flags))

        radius = 0.0
        axis = np.zeros(3)

        # Extract cylinder-specific geometric information.
        if surface_type == GeomAbs_Cylinder:

            cylinder = adaptor.Cylinder()
            radius = cylinder.Radius()

            direction = cylinder.Axis().Direction()
            axis = np.array([
                direction.X(),
                direction.Y(),
                direction.Z()
            ])

        # Extract cone-specific axis information.
        elif surface_type == GeomAbs_Cone:

            direction = adaptor.Cone().Axis().Direction()
            axis = np.array([
                direction.X(),
                direction.Y(),
                direction.Z()
            ])

        # Extract sphere-specific radius information.
        elif surface_type == GeomAbs_Sphere:

            radius = adaptor.Sphere().Radius()

        # Assemble the 14 face features in their original order.
        features = (
            flags +
            [area / diag**2, radius / diag] +
            list(axis) +
            list(centroid)
        )

        face_features.append(features)

    face_features = np.asarray(face_features, dtype=np.float32)

    # ============================================================
    # B. EDGE FEATURES: 4 values per edge
    # ============================================================

    edge_features = []

    for edge_shape in edges:

        edge = TopoDS.Edge_s(edge_shape)

        # Calculate the edge length.
        props = GProp_GProps()
        BRepGProp.LinearProperties_s(edge, props)

        length = props.Mass()

        # Determine the curve type.
        curve_type = BRepAdaptor_Curve(edge).GetType()

        is_line = float(curve_type == GeomAbs_Line)
        is_circle = float(curve_type == GeomAbs_Circle)

        # Assemble the four edge features.
        edge_features.append([
            length / diag,
            is_line,
            is_circle,
            1.0 - is_line - is_circle
        ])

    edge_features = np.asarray(edge_features, dtype=np.float32)

    # ============================================================
    # C. VERTEX FEATURES: 3 values per vertex
    # ============================================================

    vertex_features = []

    for vertex_shape in vertices:

        # Extract the original 3D vertex coordinate.
        point = BRep_Tool.Pnt_s(
            TopoDS.Vertex_s(vertex_shape)
        )

        coordinates = np.array([
            point.X(),
            point.Y(),
            point.Z()
        ])

        # Centre and normalize the coordinates.
        vertex_features.append(
            (coordinates - center) / diag
        )

    vertex_features = np.asarray(
        vertex_features,
        dtype=np.float32
    )

    # ============================================================
    # D. RECONSTRUCT B-REP INCIDENCE RELATIONSHIPS
    # ============================================================

    n_faces = len(faces)
    n_edges = len(edges)
    n_vertices = len(vertices)

    # Each edge records which faces use it.
    edge_to_faces = {
        i: set() for i in range(n_edges)
    }

    # Each edge records its endpoint vertices.
    edge_to_vertices = {
        i: set() for i in range(n_edges)
    }

    # Each vertex records the edges meeting there.
    vertex_to_edges = {
        i: set() for i in range(n_vertices)
    }

    # Each face records its boundary edges.
    face_to_edges = [
        set() for _ in range(n_faces)
    ]

    # Reconstruct face-edge relationships.
    for face_index, face_shape in enumerate(faces):

        local_map, _ = independent_entity_map(
            face_shape, TopAbs_EDGE
        )

        for j in range(1, local_map.Extent() + 1):

            local_edge = local_map.FindKey(j)

            # Convert the local edge into its global model index.
            edge_index = edge_map.FindIndex(local_edge) - 1

            if edge_index >= 0:

                face_to_edges[face_index].add(edge_index)
                edge_to_faces[edge_index].add(face_index)

    # Reconstruct edge-vertex relationships.
    for edge_index, edge_shape in enumerate(edges):

        local_map, _ = independent_entity_map(
            edge_shape, TopAbs_VERTEX
        )

        for j in range(1, local_map.Extent() + 1):

            local_vertex = local_map.FindKey(j)

            # Convert the local vertex into its global model index.
            vertex_index = vertex_map.FindIndex(local_vertex) - 1

            if vertex_index >= 0:

                edge_to_vertices[edge_index].add(vertex_index)
                vertex_to_edges[vertex_index].add(edge_index)

    # Return all reference information for this model.
    return {
        "face_x": face_features,
        "edge_x": edge_features,
        "vertex_x": vertex_features,
        "edge_to_faces": edge_to_faces,
        "edge_to_vertices": edge_to_vertices,
        "vertex_to_edges": vertex_to_edges,
        "face_to_edges": face_to_edges,
        "counts": (n_faces, n_edges, n_vertices),
        "diag": diag
    }


