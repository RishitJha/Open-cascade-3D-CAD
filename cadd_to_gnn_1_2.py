def get_entities(shape, kind):
    """
    Return unique B-Rep entities in indexed-map order.

    The ordering is used consistently for the geometric
    descriptors calculated below.
    """

    indexed_map = TopTools_IndexedMapOfShape()

    TopExp.MapShapes_s(
        shape,
        kind,
        indexed_map
    )

    return [
        indexed_map.FindKey(i)
        for i in range(1, indexed_map.Extent() + 1)
    ]


