import torch
import torch.nn as nn
import torch.nn.functional as F

from torch_geometric.nn import GCNConv
from pathlib import Path

# ------------------------------------------------------------
# 1. CONFIGURATION
# ------------------------------------------------------------

FACE_SEED = 42

FACE_INPUT_DIM = 14
FACE_HIDDEN_DIM = 64
FACE_OUTPUT_DIM = 1

FACE_LEARNING_RATE = 0.001
FACE_DROPOUT = 0.2

FACE_EPOCHS = 300
FACE_PATIENCE = 30

FACE_DEVICE = torch.device(
    "cuda" if torch.cuda.is_available() else "cpu"
)

torch.manual_seed(FACE_SEED)

# ------------------------------------------------------------
# 2. DEFINE FACE GCN
# ------------------------------------------------------------

class FaceGCN(nn.Module):

    def __init__(self):

        super().__init__()

        # Three graph convolution layers.
        self.conv1 = GCNConv(FACE_INPUT_DIM, FACE_HIDDEN_DIM)
        self.conv2 = GCNConv(FACE_HIDDEN_DIM, FACE_HIDDEN_DIM)
        self.conv3 = GCNConv(FACE_HIDDEN_DIM, FACE_HIDDEN_DIM)

        # Regression head.
        self.regressor = nn.Sequential(
            nn.Linear(FACE_HIDDEN_DIM, 32),
            nn.ReLU(),
            nn.Linear(32, FACE_OUTPUT_DIM)
        )

    def forward(self, x, edge_index):

        x = self.conv1(x, edge_index)
        x = F.relu(x)
        x = F.dropout(
            x,
            p=FACE_DROPOUT,
            training=self.training
        )

        x = self.conv2(x, edge_index)
        x = F.relu(x)
        x = F.dropout(
            x,
            p=FACE_DROPOUT,
            training=self.training
        )

        x = self.conv3(x, edge_index)
        x = F.relu(x)

        # One graph is processed at a time.
        graph_embedding = x.mean(dim=0, keepdim=True)

        return self.regressor(graph_embedding)


# ------------------------------------------------------------
# 3. INITIALIZE INDEPENDENT FACE MODEL AND OPTIMIZER
# ------------------------------------------------------------

face_model = FaceGCN().to(FACE_DEVICE)

face_optimizer = torch.optim.Adam(
    face_model.parameters(),
    lr=FACE_LEARNING_RATE
)

face_criterion = nn.MSELoss()

# ------------------------------------------------------------
# 4. DEFINE FACE GRAPH DATA ACCESS
# ------------------------------------------------------------

face_train_graphs = graph_splits["face"]["train"]
face_validation_graphs = graph_splits["face"]["validation"]
face_test_graphs = graph_splits["face"]["test"]

# ------------------------------------------------------------
# 5. DEFINE ONE-GRAPH TRAINING FUNCTION
# ------------------------------------------------------------

def train_face_epoch():

    face_model.train()

    total_loss = 0.0

    for model_id, graph in face_train_graphs.items():

        face_optimizer.zero_grad()

        x = graph.x.float().to(FACE_DEVICE)
        edge_index = graph.edge_index.long().to(FACE_DEVICE)

        target = graph.y.float().reshape(1, 1).to(FACE_DEVICE)

        prediction = face_model(x, edge_index)

        loss = face_criterion(prediction, target)

        loss.backward()

        face_optimizer.step()

        total_loss += loss.item()

    return total_loss / len(face_train_graphs)


# ------------------------------------------------------------
# 6. DEFINE VALIDATION FUNCTION
# ------------------------------------------------------------

def validate_face():

    face_model.eval()

    total_loss = 0.0

    with torch.no_grad():

        for model_id, graph in face_validation_graphs.items():

            x = graph.x.float().to(FACE_DEVICE)
            edge_index = graph.edge_index.long().to(FACE_DEVICE)

            target = graph.y.float().reshape(1, 1).to(FACE_DEVICE)

            prediction = face_model(x, edge_index)

            loss = face_criterion(prediction, target)

            total_loss += loss.item()

    return total_loss / len(face_validation_graphs)


