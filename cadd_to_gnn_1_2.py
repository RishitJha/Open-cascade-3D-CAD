HETERO_PATIENCE = 30

# Original heterogeneous node types.
HETERO_NODE_TYPES = ["face", "edge", "vertex"]

# Original directed relation types.
HETERO_EDGE_TYPES = [
    ("face", "boundary", "edge"),
    ("edge", "belongs_to", "face"),
    ("edge", "endpoint", "vertex"),
    ("vertex", "connected_by", "edge")
]

