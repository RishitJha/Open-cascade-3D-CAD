        x = self.conv3(x, edge_index)
        x = torch.relu(x)

        # Convert all edge-node embeddings into one graph embedding.
        graph_embedding = x.mean(dim=0, keepdim=True)

        # Predict normalized volume.
        prediction = self.regressor(graph_embedding)

        return prediction

