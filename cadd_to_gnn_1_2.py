PROJECT_DIR = Path("/content/drive/MyDrive/CAD_GNN_Project")
GRAPH_DIR   = PROJECT_DIR / "graphs"

# ---------------------------------------------------------------------
# PART 1: Load the dataset, your split, and the saved graphs
# ---------------------------------------------------------------------
dataset = pd.read_csv(PROJECT_DIR / "dataset_100.csv")
split   = pd.read_csv(PROJECT_DIR / "audit_reports" / "shared_split_100.csv")

